def _stamp(path: Path, tags: dict) -> None:
    with ExifTool(find_exiftool()) as tool:
        args = ["-overwrite_original"]
        for key, value in tags.items():
            args.extend([f"-{key}={value}"])
        args.append(str(path))
        tool.execute(args)


def make_library(root: Path, count: int = 40, with_pairs: bool = True) -> list[dict]:
    """Create *count* photos across a few folders with varied, known metadata."""
    root.mkdir(parents=True, exist_ok=True)
    folders = [root, root / "2024" / "mayo", root / "2024" / "junio", root / "vacaciones"]
    created: list[dict] = []
    with ExifTool(find_exiftool()) as tool:
        for index in range(count):
            folder = folders[index % len(folders)]
            folder.mkdir(parents=True, exist_ok=True)
            camera = CAMERAS[index % len(CAMERAS)]
            lens = LENSES[index % len(LENSES)]
            iso = ISOS[index % len(ISOS)]
            shutter = SHUTTERS[index % len(SHUTTERS)]
            fnumber = FSTOPS[index % len(FSTOPS)]
            focal = FOCALS[index % len(FOCALS)]
            month = 5 + (index % 3)
            day = 1 + (index % 27)
            fired = "On, Fired" if index % 5 == 0 else "Off, Did not fire"
            name = f"IMG_{4000 + index:04d}.jpg"
            path = folder / name
            path.write_bytes(TINY_JPEG)
            args = [
                "-overwrite_original",
                f"-Model={camera}",
                f"-LensModel={lens}",
                f"-ISO={iso}",
                f"-ExposureTime={shutter}",
                f"-FNumber={fnumber}",
                f"-FocalLength={focal}",
                f"-Flash={fired}",
                f"-DateTimeOriginal=2024:{month:02d}:{day:02d} 12:33:21",
                f"-CreateDate=2024:{month:02d}:{day:02d} 12:33:21",
                str(path),
            ]
            tool.execute(args)
            created.append({
                "path": path, "camera": camera, "lens": lens, "iso": iso,
                "shutter": shutter, "fnumber": fnumber, "focal": focal,
                "fired": index % 5 == 0, "month": month, "name": name,
            })
            # A RAW sibling for every third photo: only one of the pair counts.
            if with_pairs and index % 3 == 0:
                raw = folder / name.replace(".jpg", ".cr2")
                shutil.copy2(path, raw)  # same frame, RAW extension: RAW wins
                created.append({"path": raw, "companion": True})
    return created


