@pytest.fixture(scope="session", autouse=True)
def isolated_settings(tmp_path_factory):
    """Point every AppConfig in the suite at a throwaway ini file.

    QSettings on macOS writes to a plist in ~/Library/Preferences and ignores
    both setDefaultFormat and setPath, so redirecting it the documented way does
    not work. Swapping the class that constructs it does: without this, running
    the tests overwrites the real theme, language and recent-folder list.
    """
    qsettings = pytest.importorskip("PySide6.QtCore").QSettings
    from photostats.core import config as config_module

    scratch = tmp_path_factory.mktemp("settings")
    real = config_module.QSettings
    counter = [0]

    def isolated(*args, **kwargs):
        counter[0] += 1
        kwargs.pop("scope", None)
        return real(str(scratch / f"s{counter[0]}.ini"), qsettings.IniFormat)

    config_module.QSettings = isolated
    yield
    config_module.QSettings = real


